/** Presentation wording for backend provenance and research labels. Raw protocol values stay intact. */
export function displayCopy(value: string | null | undefined): string {
	if (!value) return '';
	return value
		.replace(/NHM_VIRTUAL_WEARABLE_(\d+)/g, 'NHM software ECG source $1')
		.replace(/VIRTUAL_WEARABLE/g, 'Software ECG source')
		.replace(/NOT_IN_SANDBOX/g, 'Not in research workspace')
		.replace(/SYNTHETIC_COHORT/g, 'Research cohort')
		.replace(/WEARABLE_SIM_V1/g, 'Software ECG source v1')
		.replace(/WEARABLE_SIM_[A-Z0-9_]+/g, 'Software ECG research source')
		.replace(/SYNTHETIC_PHYSIOLOGY/g, 'Software-generated ECG')
		.replace(/SHORTLISTED_FOR_SANDBOX_REUSE/g, 'Shortlisted for research reuse')
		.replace(/ACCEPTED_TO_SANDBOX/g, 'Accepted for research review')
		.replace(/IN_SANDBOX/g, 'In research workspace')
		.replace(/SIM_FL_SITE_(\d+)/g, 'Logical site $1')
		.replace(/SYNTHETIC_VIRTUAL_WEARABLE/g, 'Software ECG source')
		.replace(/CANONICAL_SYNTHETIC/g, 'Canonical research cohort')
		.replace(/RECORDED_SYNTHETIC/g, 'Recorded research evidence')
		.replaceAll('SYNTHETIC_ENGINEERING_EVENT_EVALUATION_ONLY_NOT_AAMI_SVF_OR_CLINICAL', 'Research-event evaluation only · not AAMI-SVF or clinical validation')
		.replace(/REUSED SYNTHETIC DIAGNOSTIC EVALUATION/gi, 'REUSED RESEARCH EVALUATION')
		.replace(/local synthetic buffer/gi, 'local research-window buffer')
		.replace(/synthetic-only evidence/gi, 'Evidence from software-generated ECG only')
		.replace(/synthetic-only/gi, 'software-generated ECG only')
		.replace(/synthetic (?:engineering )?event(?:s|-label)?/gi, 'assigned research event')
		.replace(/synthetic physiology/gi, 'software-generated ECG')
		.replace(/synthetic transport/gi, 'software ECG transport')
		.replace(/synthetic research partitions/gi, 'logical research partitions')
		.replace(/synthetic (?:assigned )?labels/gi, 'algorithmically assigned labels')
		.replace(/LABELS ARE SYNTHETIC/g, 'LABELS ARE ALGORITHMICALLY ASSIGNED')
		.replace(/labels are synthetic/gi, 'labels are algorithmically assigned')
		.replace(/synthetic participant clusters/gi, 'generated participant clusters')
		.replace(/synthetic participants/gi, 'generated research participants')
		.replace(/synthetic participant/gi, 'generated research participant')
		.replace(/synthetic (?:logical )?clients/gi, 'logical clients')
		.replace(/synthetic sites/gi, 'logical sites')
		.replace(/synthetic (?:cohort )?peers/gi, 'research peers')
		.replace(/synthetic cohort/gi, 'research cohort')
		.replace(/synthetic ECG/gi, 'software-generated ECG')
		.replace(/simulated ECG/gi, 'software-generated ECG')
		.replace(/simulated[- ]wearable/gi, 'software ECG source')
		.replace(/simulated site/gi, 'logical site')
		.replace(/simulated source/gi, 'software source')
		.replace(/single-host simulation/gi, 'single-host research run')
		.replace(/simulator/gi, 'software ECG generator')
		.replace(/simulating/gi, 'recreating in software')
		.replace(/simulate/gi, 'recreate in software')
		.replace(/virtual wearable/gi, 'software ECG source')
		.replace(/virtual source/gi, 'software source')
		.replace(/virtual device/gi, 'software device')
		.replace(/test source/gi, 'software ECG source')
		.replace(/engineering sandbox/gi, 'research workspace')
		.replace(/sandbox/gi, 'research workspace')
		.replace(/\btoy\b/gi, 'small research model')
		.replace(/\bfake\b/gi, 'placeholder')
		.replace(/\bfabricat(?:ed|ion)\b/gi, 'unsupported')
		.replace(/synthetic/gi, 'software-generated')
		.replace(/simulated/gi, 'software-based')
		.replace(/simulation/gi, 'software-source run')
		.replace(/\bvirtual\b/gi, 'software');
}
